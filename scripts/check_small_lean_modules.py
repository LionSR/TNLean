#!/usr/bin/env python3
"""Keep the number of small Lean modules of each directory under a ceiling.

A module holds one coherent interface: the definition of an object and the
facts about it, or one theorem with the lemmas only it uses.  A module of one
or two declarations is merged into the module of its object.  This check
counts, for each directory, the modules that are still that small, and fails
when a count rises above the ceiling recorded in ``CEILINGS_PATH``.

A module is small when it has at most ``MAX_DECLARATIONS`` public top-level
declarations.  The reading is lexical, after comments are removed and string
contents are masked: a declaration is a ``theorem``, ``lemma``, ``def``,
``abbrev``, ``structure``, ``class``, ``instance``, ``inductive``, ``opaque``,
``axiom``, ``irreducible_def`` or ``alias`` that starts in the first column,
after any attributes and modifiers; one marked ``private`` is not counted.
Generated aggregators and other import-only modules are not counted, nor are
the modules of ``TNLean/Archive``.  A module with no counted declaration (one
that declares only notation, say) is small.

The directory of a module is that of ``check_import_layers.directory_of``: its
first two path components below ``TNLean/MPS`` and ``TNLean/PEPS``, its first
component elsewhere, and ``.`` for a module directly below ``TNLean/``.  A
directory without a recorded ceiling has ceiling 0.

The ceilings may only fall.  ``--write`` lowers each one to the current count
and never raises one.  With ``--base-ref`` the ceilings are also compared with
the file at the merge base: a ceiling may exceed its value there only by the
number of small modules that Git records as moved into the directory from
another one, and the sum of the ceilings may not rise.  So a move carries its
ceiling along, and a new small module cannot be admitted by recording it.
"""

from __future__ import annotations

import argparse
import re
import subprocess
from collections import Counter
from collections.abc import Mapping
from pathlib import Path

from check_import_layers import IMPORT_COMMAND_RE, directory_of, renamed_modules, tracked_sources

CEILINGS_PATH = "scripts/small_lean_module_ceilings.txt"
MAX_DECLARATIONS = 2
AGGREGATOR_MARKER = "This file is generated by scripts/generate_import_aggregators.py."

CHAR_LITERAL_RE = re.compile(r"'(?:\\[^'\n]+|[^'\\\n])'")
RAW_STRING_START_RE = re.compile(r'r(#+)?"')
# Where a branch of `strip_comments_and_strings` other than the verbatim copy can
# apply, outside and inside a block comment; the loop jumps from one to the next.
OPENER_RE = re.compile(r"[«'\"]|r#*\"|/-|--")
COMMENT_DELIMITER_RE = re.compile(r"/-|-/")
DECLARATION_RE = re.compile(
    r"^(?:@\[[^\]]*(?:\[[^\]]*\][^\]]*)*\]\s*)*"
    r"(?P<mods>(?:(?:private|protected|noncomputable|partial|unsafe|nonrec|scoped|local|public)"
    r"\s+)*)"
    r"(?:class\s+inductive|class\s+abbrev|theorem|lemma|def|abbrev|structure|class|instance"
    r"|inductive|opaque|axiom|irreducible_def|alias)\b",
    re.M,
)

HEADER = """\
# Ceilings on the number of small Lean modules per directory of TNLean, read by
# scripts/check_small_lean_modules.py.  A small module has at most two public
# top-level declarations; it is merged into the module of its object.  A
# directory not listed here has ceiling 0.  The ceilings may only fall: lower
# them with `python3 scripts/check_small_lean_modules.py --write`, and when a
# small module moves to another directory, move its ceiling with it.
"""


def strip_comments_and_strings(source: str) -> str:
    """Remove comments and blank out string contents, keeping every newline."""
    out: list[str] = []
    index, depth, length = 0, 0, len(source)

    def blank(text: str) -> str:
        return "".join("\n" if character == "\n" else " " for character in text)

    while index < length:
        if depth:
            # Inside a block comment only the nesting delimiters and newlines matter.
            m = COMMENT_DELIMITER_RE.search(source, index)
            stop = length if m is None else m.start()
            out.append("\n" * source.count("\n", index, stop))
            if m is None:
                break
            depth += 1 if m.group() == "/-" else -1
            index = m.end()
            continue
        m = OPENER_RE.search(source, index)
        if m is None:
            out.append(source[index:])
            break
        out.append(source[index:m.start()])
        index = m.start()
        pair = source[index:index + 2]
        character = source[index]
        after_word = index > 0 and (source[index - 1].isalnum() or source[index - 1] in "_'")
        if character == "«":
            end = source.find("»", index + 1)
            end = length - 1 if end == -1 else end
            out.append(source[index:end + 1])
            index = end + 1
        elif character == "'" and not after_word and (m := CHAR_LITERAL_RE.match(source, index)):
            out.append("' '")
            index = m.end()
        elif character == "r" and not after_word and (m := RAW_STRING_START_RE.match(source, index)):
            delimiter = '"' + (m.group(1) or "")
            end = source.find(delimiter, m.end())
            end = length if end == -1 else end + len(delimiter)
            out.append('"' + blank(source[index:end]) + '"')
            index = end
        elif character == '"':
            out.append('"')
            index += 1
            while index < length:
                if source[index] == '"':
                    out.append('"')
                    index += 1
                    break
                step = 2 if source[index] == "\\" and index + 1 < length else 1
                out.append(blank(source[index:index + step]))
                index += step
        elif pair == "/-":
            out.append(" ")
            depth = 1
            index += 2
        elif pair == "--":
            newline = source.find("\n", index + 2)
            if newline == -1:
                index = length
            else:
                out.append("\n")
                index = newline + 1
        else:
            out.append(character)
            index += 1
    return "".join(out)


def public_declarations(source: str) -> int | None:
    """Return the number of public top-level declarations, or ``None`` for an aggregator.

    An aggregator is a generated one or any module whose code is only imports.
    """
    if AGGREGATOR_MARKER in source[:1024]:
        return None
    stripped = strip_comments_and_strings(source)
    lines = [line for line in stripped.split("\n") if line.strip()]
    if lines and all(IMPORT_COMMAND_RE.fullmatch(line.strip()) for line in lines):
        return None
    return sum(
        "private" not in m.group("mods").split() for m in DECLARATION_RE.finditer(stripped)
    )


def directory(module: str) -> str:
    return directory_of(module) or "."


def small_modules(sources: Mapping[str, str]) -> dict[str, dict[str, int]]:
    """Return, per directory, each small module with its number of public declarations."""
    found: dict[str, dict[str, int]] = {}
    for module in sorted(sources):
        count = public_declarations(sources[module])
        if count is not None and count <= MAX_DECLARATIONS:
            found.setdefault(directory(module), {})[module] = count
    return found


def parse_ceilings(text: str) -> dict[str, int]:
    """Read ``directory count`` lines; ``#`` starts a comment."""
    ceilings: dict[str, int] = {}
    for number, line in enumerate(text.splitlines(), start=1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2 or not parts[1].isdigit():
            raise ValueError(f"line {number}: expected `directory count`, got {line!r}")
        if parts[0] in ceilings:
            raise ValueError(f"line {number}: directory {parts[0]} is listed twice")
        ceilings[parts[0]] = int(parts[1])
    return ceilings


def format_ceilings(ceilings: Mapping[str, int]) -> str:
    rows = sorted((d, c) for d, c in ceilings.items() if c > 0)
    width = max((len(d) for d, _ in rows), default=0)
    return HEADER + "".join(f"{d.ljust(width)} {c}\n" for d, c in rows)


def lowered(ceilings: Mapping[str, int], counts: Mapping[str, int]) -> dict[str, int]:
    """Lower each ceiling to the current count; never raise one, never add a directory."""
    result: dict[str, int] = {}
    for d, c in ceilings.items():
        ceiling = min(c, counts.get(d, 0))
        if ceiling:
            result[d] = ceiling
    return result


def check(
    small: Mapping[str, Mapping[str, int]],
    ceilings: Mapping[str, int],
    base: Mapping[str, int] | None = None,
    moved_in: Mapping[str, int] | None = None,
    changed: set[str] | None = None,
) -> tuple[list[str], list[str]]:
    """Return the errors and warnings of the check.

    ``base`` is the file at the merge base (``None`` while the file is being
    introduced), ``moved_in`` the number of small modules moved into each
    directory since then, and ``changed`` the modules added or changed since
    then, which an error names in preference to the others.
    """
    errors: list[str] = []
    warnings: list[str] = []
    for d in sorted(set(small) | set(ceilings)):
        modules = small.get(d, {})
        ceiling = ceilings.get(d, 0)
        if len(modules) > ceiling:
            named = [m for m in modules if changed is None or m in changed] or list(modules)
            listing = ", ".join(f"{m} ({modules[m]})" for m in named)
            label = "added or changed" if changed is not None and named != list(modules) else "small"
            errors.append(
                f"{d} has {len(modules)} modules of at most {MAX_DECLARATIONS} public "
                f"declarations, above its ceiling of {ceiling}; {label} modules: {listing}"
            )
        elif len(modules) < ceiling:
            warnings.append(
                f"{d} has {len(modules)} small modules, below its ceiling of {ceiling}; "
                "lower the ceiling with --write"
            )
    if base is not None:
        moved_in = moved_in or {}
        for d in sorted(ceilings):
            allowed = base.get(d, 0) + moved_in.get(d, 0)
            if ceilings[d] > allowed:
                errors.append(
                    f"Ceiling of {d} rose from {base.get(d, 0)} to {ceilings[d]}"
                    + (f" with {moved_in[d]} small modules moved in" if moved_in.get(d) else "")
                    + "; a ceiling may only fall"
                )
        if sum(ceilings.values()) > sum(base.values()):
            errors.append(
                f"Sum of the ceilings rose from {sum(base.values())} to "
                f"{sum(ceilings.values())}; when a small module moves, lower the ceiling "
                "of the directory it left"
            )
    return errors, warnings


def git(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(root), *args], check=False, capture_output=True, text=True
    )


def base_state(
    root: Path, base_ref: str, small: Mapping[str, Mapping[str, int]]
) -> tuple[dict[str, int] | None, dict[str, int], set[str]]:
    """Return the ceilings at the merge base, the moves into each directory and the changed modules."""
    merge_base = git(root, "merge-base", "HEAD", base_ref)
    if merge_base.returncode != 0:
        raise ValueError(f"cannot find merge base with {base_ref}: {merge_base.stderr.strip()}")
    commit = merge_base.stdout.strip()
    shown = git(root, "show", f"{commit}:{CEILINGS_PATH}")
    if shown.returncode == 0:
        base = parse_ceilings(shown.stdout)
    elif "does not exist in" in shown.stderr or "exists on disk, but not in" in shown.stderr:
        base = None  # the file is being introduced
    else:
        raise ValueError(f"cannot read {CEILINGS_PATH} at {commit}: {shown.stderr.strip()}")
    current = {m: d for d, modules in small.items() for m in modules}
    moved_in: Counter[str] = Counter(
        current[new]
        for old, new in renamed_modules(root, commit).items()
        if new in current and directory(old) != current[new]
    )
    listing = git(root, "diff", "--name-only", "--diff-filter=AMR", commit, "--", "TNLean")
    if listing.returncode != 0:
        raise ValueError(f"cannot list the modules changed since {commit}: {listing.stderr.strip()}")
    changed = {
        path.removesuffix(".lean").replace("/", ".")
        for path in listing.stdout.splitlines()
        if path.endswith(".lean")
    }
    return base, dict(moved_in), changed


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Keep the number of modules of at most two public declarations of each "
        "directory under its recorded ceiling."
    )
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument(
        "--base-ref", help="ref whose merge base with HEAD fixes the ceilings that may not rise"
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="lower the recorded ceilings to the current counts (never raises one)",
    )
    parser.add_argument(
        "--list", action="store_true", help="print the small modules of each directory and exit"
    )
    args = parser.parse_args()
    root = args.root.resolve()
    small = small_modules(tracked_sources(root))
    counts = {d: len(modules) for d, modules in small.items()}

    if args.list:
        for d, modules in sorted(small.items()):
            print(f"{d} ({len(modules)})")
            for module, count in modules.items():
                print(f"  {module} ({count})")
        return 0

    path = root / CEILINGS_PATH
    try:
        ceilings = parse_ceilings(path.read_text(encoding="utf-8")) if path.exists() else None
    except ValueError as error:
        print(f"::error file={CEILINGS_PATH},title=Small-module ceilings::{error}")
        return 1
    if args.write:
        # A missing file is created from the current counts; an existing one only falls.
        ceilings = dict(counts) if ceilings is None else lowered(ceilings, counts)
        path.write_text(format_ceilings(ceilings), encoding="utf-8")
        print(f"Wrote {CEILINGS_PATH}: ceilings summing to {sum(ceilings.values())} in "
              f"{len(ceilings)} directories.")
    ceilings = ceilings or {}

    base = moved_in = changed = None
    if args.base_ref is not None:
        try:
            base, moved_in, changed = base_state(root, args.base_ref, small)
        except (ValueError, subprocess.CalledProcessError) as error:
            print(f"::error title=Small-module check failed::{error}")
            return 1

    errors, warnings = check(small, ceilings, base, moved_in, changed)
    for message in warnings:
        print(f"::warning file={CEILINGS_PATH},title=Small-module ceiling::{message}")
    for message in errors:
        print(f"::error file={CEILINGS_PATH},title=Small-module ceiling::{message}")
    if errors:
        print(
            "A module holds one coherent interface: a module of one or two declarations is "
            "merged into the module of its object. The ceilings in "
            f"{CEILINGS_PATH} may only fall; see docs/ci-automation.md."
        )
        return 1
    print(
        f"{sum(counts.values())} small modules in {len(counts)} directories, none above "
        f"its ceiling (recorded total {sum(ceilings.values())})."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
