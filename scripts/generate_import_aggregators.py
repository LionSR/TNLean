#!/usr/bin/env python3
"""Generate and check hierarchical pure-import aggregators for TNLean.

Every production directory without a pre-existing module of the same name gets
an aggregator.  A pre-existing same-name module is left untouched; its nearest
generated ancestor imports both that module and the uncovered descendant
frontier.  This handles legacy file/directory name collisions without renames.

``TNLean/Archive`` is intentionally outside the production library manifest.
"""

from __future__ import annotations

import argparse
from collections.abc import Iterable
from pathlib import Path
import re
import sys

from lean_import_syntax import pure_import_modules

GENERATED_MARKER = "This file is generated by scripts/generate_import_aggregators.py."
GENERATED_MARKER_RE = re.compile(
    rf"(?m)^(?:--|/-)\s*{re.escape(GENERATED_MARKER)}(?:\s|$)"
)
GENERATED_NOTICE = (
    "/-\n"
    "Copyright (c) 2026 TNLean contributors. All rights reserved.\n"
    "Released under Apache 2.0 license as described in the file LICENSE.\n"
    "Authors: TNLean contributors\n"
    "-/\n"
    f"-- {GENERATED_MARKER}\n"
    "-- Do not edit it directly; run the generator instead.\n"
    "-- Import architecture: docs/import_structure.md.\n"
)
EXCLUDED_TOP_LEVEL_DIRECTORIES = frozenset({"Archive"})


def is_aggregator_path(path: Path, source_root: Path) -> bool:
    """Return whether ``path`` has root or directory-aggregator provenance."""
    if path == source_root.parent / f"{source_root.name}.lean":
        return True
    try:
        path.relative_to(source_root)
    except ValueError:
        return False
    return path.suffix == ".lean" and path.with_suffix("").is_dir()


def is_generated(path: Path, source_root: Path) -> bool:
    """Recognize generated files only by marker, pure imports, and path provenance."""
    if not is_aggregator_path(path, source_root):
        return False
    try:
        content = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return False
    if GENERATED_MARKER_RE.search(content[:1024]) is None:
        return False
    _, error = pure_import_modules(content)
    return error is None


def module_name(path: Path, repository_root: Path) -> str:
    """Convert a repository-relative Lean source path to its module name."""
    return ".".join(path.relative_to(repository_root).with_suffix("").parts)


def is_excluded(path: Path, source_root: Path) -> bool:
    """Return whether ``path`` lies in an intentionally unbuilt subtree."""
    relative = path.relative_to(source_root)
    return bool(relative.parts) and relative.parts[0] in EXCLUDED_TOP_LEVEL_DIRECTORIES


def production_sources(source_root: Path) -> list[Path]:
    """List handwritten production Lean sources in deterministic order."""
    return sorted(
        path
        for path in source_root.rglob("*.lean")
        if not is_excluded(path, source_root) and not is_generated(path, source_root)
    )


def source_directories(sources: Iterable[Path], source_root: Path) -> set[Path]:
    """Return all source-containing directories, including their ancestors."""
    directories = {source_root}
    for source in sources:
        directory = source.parent
        while directory != source_root:
            directories.add(directory)
            directory = directory.parent
    return directories


def aggregator_path(directory: Path, source_root: Path, repository_root: Path) -> Path:
    """Return the aggregator path associated with ``directory``."""
    if directory == source_root:
        return repository_root / f"{source_root.name}.lean"
    return directory.with_suffix(".lean")


def build_expected_files(repository_root: Path) -> tuple[dict[Path, str], list[Path]]:
    """Compute generated file contents and the handwritten production sources."""
    source_root = repository_root / "TNLean"
    sources = production_sources(source_root)
    directories = source_directories(sources, source_root)
    source_set = set(sources)

    generated_directories: set[Path] = {source_root}
    blocked_directories: set[Path] = set()
    for directory in directories - {source_root}:
        candidate = aggregator_path(directory, source_root, repository_root)
        if candidate in source_set:
            blocked_directories.add(directory)
        else:
            generated_directories.add(directory)

    children: dict[Path, list[Path]] = {directory: [] for directory in directories}
    for directory in directories - {source_root}:
        parent = directory.parent
        if parent in children:
            children[parent].append(directory)
    for values in children.values():
        values.sort()

    direct_sources: dict[Path, list[Path]] = {directory: [] for directory in directories}
    for source in sources:
        direct_sources[source.parent].append(source)
    for values in direct_sources.values():
        values.sort()

    def frontier(directory: Path) -> set[Path]:
        """Modules an ancestor must import to cover ``directory``."""
        if directory in generated_directories:
            return {aggregator_path(directory, source_root, repository_root)}
        assert directory in blocked_directories
        result = {aggregator_path(directory, source_root, repository_root)}
        result.update(direct_sources[directory])
        for child in children[directory]:
            result.update(frontier(child))
        return result

    expected: dict[Path, str] = {}
    for directory in sorted(generated_directories):
        imports = set(direct_sources[directory])
        for child in children[directory]:
            imports.update(frontier(child))
        target = aggregator_path(directory, source_root, repository_root)
        imports.discard(target)
        names = sorted(module_name(path, repository_root) for path in imports)
        body = "".join(f"import {name}\n" for name in names)
        expected[target] = f"{GENERATED_NOTICE}\n{body}"

    return expected, sources


def imported_modules(text: str) -> set[str]:
    """Extract imports when ``text`` has the generated pure-import shape."""
    modules, error = pure_import_modules(text)
    return set(modules) if error is None else set()


def check_manifest_coverage(
    repository_root: Path, expected: dict[Path, str], sources: list[Path]
) -> list[str]:
    """Return sources absent from the generated hierarchical frontier.

    Only generated aggregator imports are traversed.  Imports in handwritten
    modules deliberately do not count: incidental reachability must not hide a
    missing explicit entry in the generated manifest.
    """
    generated_imports = {
        module_name(path, repository_root): imported_modules(content)
        for path, content in expected.items()
    }
    production_modules = {module_name(path, repository_root) for path in sources}
    represented: set[str] = set()
    visited_aggregators: set[str] = set()
    pending = ["TNLean"]
    while pending:
        current = pending.pop()
        if current in visited_aggregators:
            continue
        visited_aggregators.add(current)
        for imported in generated_imports.get(current, ()):
            if imported in production_modules:
                represented.add(imported)
            if imported in generated_imports:
                pending.append(imported)
    return sorted(production_modules - represented)


def update(repository_root: Path, check: bool) -> int:
    """Write expected aggregators, or check that the working tree has them exactly."""
    expected, sources = build_expected_files(repository_root)
    source_root = repository_root / "TNLean"
    root_aggregator = repository_root / "TNLean.lean"
    existing_generated = {
        path
        for path in [root_aggregator, *source_root.rglob("*.lean")]
        if is_generated(path, source_root)
    }

    problems: list[str] = []
    for path, content in sorted(expected.items()):
        relative = path.relative_to(repository_root)
        if not path.exists():
            problems.append(f"missing generated aggregator: {relative}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"out-of-date generated aggregator: {relative}")

    stale = sorted(existing_generated - expected.keys())
    problems.extend(
        f"stale generated aggregator: {path.relative_to(repository_root)}" for path in stale
    )
    coverage_problems = [
        f"production module is absent from the generated import frontier: {name}"
        for name in check_manifest_coverage(repository_root, expected, sources)
    ]
    problems.extend(coverage_problems)

    if check:
        if problems:
            for problem in problems:
                print(problem)
            print("Run: python3 scripts/generate_import_aggregators.py")
            return 1
        print(
            f"Import aggregators are current: {len(expected)} generated files cover "
            f"{len(sources)} production modules."
        )
        return 0

    if coverage_problems:
        for problem in coverage_problems:
            print(problem)
        return 1

    for path in stale:
        print(f"Removing {path.relative_to(repository_root)}")
        path.unlink()
    for path, content in sorted(expected.items()):
        relative = path.relative_to(repository_root)
        old_content = path.read_text(encoding="utf-8") if path.exists() else None
        if old_content != content:
            print(f"{'Updating' if path.exists() else 'Creating'} {relative}")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print(
        f"Generated {len(expected)} import aggregators covering "
        f"{len(sources)} production modules."
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=Path("."), help="repository root (default: .)"
    )
    parser.add_argument(
        "--check", action="store_true", help="check generated files without changing them"
    )
    args = parser.parse_args()
    return update(args.root.resolve(), args.check)


if __name__ == "__main__":
    sys.exit(main())
